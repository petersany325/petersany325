    /** @return array<string, mixed>|null */
    public static function service(string $slug): ?array
    {
        foreach (self::services() as $row) {
            if ($row['slug'] === $slug) {
                return $row;
            }
        }

        return null;
    }

    /** @return array{label:string,url:string,children:list<array<string,mixed>>} */
    public static function navItem(): array
    {
        $services = [];
        foreach (self::services() as $row) {
            $services[] = ['label' => $row['title'], 'url' => '/design/'.$row['slug']];
        }

        return [
            'label' => 'طراحی سایت',
            'url' => '/design',
            'children' => [
                [
                    'label' => 'خدمات طراحی',
                    'url' => '/design#services',
                    'children' => $services,
                ],
                [
                    'label' => 'همکاری',
                    'url' => '/design#cta',
                    'children' => [
                        ['label' => 'درباره ما', 'url' => '/about'],
