    /** @return array<string, mixed>|null */
    public static function service(string $slug): ?array
    {
        foreach (self::services() as $row) {
            if ($row['slug'] === $slug) {
                return $row;
            }
        }

        return null;
    }

    /** @return array{label:string,url:string,children:list<array<string,mixed>>} */
    public static function navItem(): array
    {
        $services = [];
        foreach (self::services() as $row) {
            $services[] = [
                'label' => self::builderLabel('/design/'.$row['slug'], $row['title']),
                'url' => '/design/'.$row['slug'],
            ];
        }

        return [
            'label' => self::builderLabel('/design', 'طراحی سایت'),
            'url' => '/design',
            'children' => [
                [
                    'label' => 'خدمات طراحی',
                    'url' => '/design#services',
                    'children' => $services,
                ],
            ],
        ];
    }

    protected static function builderLabel(string $path, string $fallback): string
    {
        try {
            if (! class_exists(\Plugins\ThemeBuilder\src\PageBuilder::class)) {
                return $fallback;
            }
            $page = \Plugins\ThemeBuilder\src\PageBuilder::findByPath($path);
            $label = trim((string) ($page['menu_label'] ?? ''));

            return $label !== '' ? $label : $fallback;
        } catch (\Throwable) {
            return $fallback;
        }
    }
