    /**
     * @return array<string, mixed>
     */
    public static function of(string $slug): array
    {
        return match ($slug) {
            'corporate' => self::corporate(),
            'shop' => self::shop(),
            'supermarket' => self::supermarket(),
            'distribution' => self::distribution(),
            'restaurant' => self::restaurant(),
            'cafe' => self::cafe(),
            'manufacturing' => self::manufacturing(),
            'contracting' => self::contracting(),
            'service' => self::service(),
            'technicians' => self::technicians(),
            'automation' => self::automation(),
            default => [],
        };
    }

    /**
     * @param  array<string, mixed>  $row
     * @return array<string, mixed>
     */
    public static function merge(array $row): array
    {
        $cat = self::of((string) ($row['slug'] ?? ''));
        if ($cat === []) {
            return $row;
        }
        foreach (['tagline', 'product_code', 'version', 'stats', 'strengths', 'options', 'compare', 'day', 'audience', 'pains'] as $key) {
            if (isset($cat[$key])) {
                $row[$key] = $cat[$key];
            }
        }
        if (! empty($cat['highlights'])) {
            $row['highlights'] = $cat['highlights'];
        }
        $have = [];
        foreach ($row['menus'] ?? [] as $item) {
            $have[(string) ($item['title'] ?? '')] = true;
        }
        foreach ($cat['options'] ?? [] as $item) {
            $title = (string) ($item['title'] ?? '');
            if ($title === '' || isset($have[$title])) {
                continue;
            }
            $row['menus'][] = $item;
            $have[$title] = true;
        }

        return $row;
    }

    /**
     * Nested items under one accounting edition in the header menu.
     *
     * @return list<array{label:string,url:string}>
     */
    public static function navLeaves(string $slug): array
    {
        $base = '/computer-accounting/'.$slug;
        $cat = self::of($slug);
        $leaves = [
            ['label' => 'نقاط قوت', 'url' => $base.'#strengths'],
            ['label' => 'امکانات منو', 'url' => $base.'#options'],
        ];
        foreach (array_slice($cat['options'] ?? [], 0, 6) as $item) {
            $leaves[] = [
                'label' => (string) ($item['title'] ?? ''),
                'url' => $base.'#options',
            ];
        }
        $leaves[] = ['label' => 'مقایسه با نرم‌افزارهای رایج', 'url' => $base.'#compare'];

        return array_values(array_filter($leaves, static fn (array $i): bool => ($i['label'] ?? '') !== ''));
    }

