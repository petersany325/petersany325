    }

    /**
     * @return list<array{label:string,url:string,children:list<array{label:string,url:string}>}>
     */
    public static function navGroups(): array
    {
        $by = [
            'بازرگانی و فروش' => ['corporate', 'shop', 'supermarket', 'distribution'],
            'رستوران و کافه' => ['restaurant', 'cafe'],
            'پروژه و تولید' => ['contracting', 'manufacturing', 'service'],
            'سازمان' => ['automation'],
        ];
        $map = [];
        foreach (self::industries() as $row) {
            $map[$row['slug']] = $row;
        }
        $groups = [];
        foreach ($by as $title => $slugs) {
            $kids = [];
            foreach ($slugs as $slug) {
                if (! isset($map[$slug])) {
                    continue;
                }
                $kids[] = ['label' => $map[$slug]['title'], 'url' => '/computer-accounting/'.$slug];
            }
            if ($title === 'سازمان') {
                $kids[] = ['label' => 'همه انواع حسابداری کامپیوتر', 'url' => '/computer-accounting#industries'];
            }
            $groups[] = ['label' => $title, 'url' => '/computer-accounting#industries', 'children' => $kids];
        }
        $mods = [];
        if (class_exists(StudioProductMenus::class)) {
            foreach (StudioProductMenus::accountingGroups() as $group) {
                $mods[] = ['label' => $group['title'], 'url' => '/computer-accounting#'.$group['slug']];
            }
        }
        $groups[] = ['label' => 'ماژول‌های دفتر', 'url' => '/computer-accounting', 'children' => $mods];

        return $groups;
    }

